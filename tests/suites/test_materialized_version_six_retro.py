"""#301 and #306's rules at #309's rendered version 6 policy seam."""

from pathlib import Path
import re

import support
from govlib import store
from materialized_version_support import VersionThreeRendered, flat
from policy_rows_319 import RUNNING_RETRO, TICKETS

CLASS_RETRO = "docs/agents/class-retro.md"


class VersionSixPlannerPolicy(VersionThreeRendered):
    VERSION = 6

    def test_miss_record_keeps_a_skills_required_opening_in_the_free_detail(self):
        body = flat(self.text("docs/agents/issue-tracker.md").split("## Miss records", 1)[1])
        self.assertIn("The body opens with these six field lines", body)
        self.assertIn("Put a skill's required opening line, such as `triage`'s disclaimer, "
                      "in the free detail after the six field lines.", body)

    def test_running_retro_states_each_discipline_once(self):
        body = flat(RUNNING_RETRO.read(self.text(RUNNING_RETRO.path)))
        for label, rule in (
            ("Level", "Propose each lesson at the highest level that works. First structure, which removes the cause, "
                      "such as stating a condition once or generating cases from one source. Then a mechanical check: "
                      "the gate, Merge watch, CI or a test. Text comes last and says why neither higher level works."),
            ("Proof", "A candidate that adds a check names the past instance the check must fail on, and its ticket "
                      "asks the delivery to show that failure. If the check cannot run on that instance in the "
                      "committed suite, demonstrate the failure outside the suite."),
            ("Recurrence", "A bug class that recurs after its fix merged has a failed fix: propose the next level up."),
            ("Deletion", "Propose deleting text whose mistake a check now prevents."),
            ("Cost", "Each candidate states the CI time, files and fixtures it adds, the policy text it adds or "
                     "removes, and whether it changes fixed content."),
            ("Cap", "Recommend at most three new tickets per retro, and list the other candidates as not recommended, "
                    "each with its reason."),
        ):
            with self.subTest(discipline=label):
                heading = "**%s.**" % label
                self.assertEqual(body.count(heading), 1)
                self.assertIn("%s %s" % (heading, rule), body)
        self.assertIn("A retro reports events, never rates.", body)
        self.assertNotIn("section's budget test", body)

    def test_running_retro_routes_the_class_retro(self):
        body = flat(RUNNING_RETRO.read(self.text(RUNNING_RETRO.path)))
        self.assertIn("For a class retro, follow [Class retro](class-retro.md).", body)

    def test_running_retro_keeps_the_miss_record_steps(self):
        body = flat(RUNNING_RETRO.read(self.text(RUNNING_RETRO.path)))
        for step in (
            "1. Read the record, the merged PR with its review threads, its evidence comment and Merge summary, "
            "and its ticket. Read session logs only when habit names them.",
            "2. Give habit the candidate lessons in Chinese, by severity, and post the English detail as a comment "
            "on the record. A confirmed process miss for a review kind makes moving that check into the governance "
            "gate the default candidate.",
            "4. Close the record, quoting habit's decision.",
        ):
            with self.subTest(step=step):
                self.assertIn(step, body)

    def test_running_retro_tickets_fixed_content_picks_back_to_the_source_issue(self):
        body = RUNNING_RETRO.read(self.text(RUNNING_RETRO.path))
        scope, step_three = re.split(r"(?m)^3\. ", body, maxsplit=1)
        step_three = flat(re.split(r"(?m)^4\. ", step_three, maxsplit=1)[0])
        for case, clause in (
            ("miss record", "Use steps 1 to 4 for a miss record."),
            ("class retro", "Step 3 also applies to a class retro."),
        ):
            with self.subTest(case=case):
                self.assertIn(clause, flat(scope))
        self.assertTrue(step_three.startswith("habit picks. Ticket each pick into one home:"))
        for source, clause in (
            ("miss record", "For a retro on a miss record, link that record."),
            ("class retro", "For a class retro, link its class retro issue."),
        ):
            with self.subTest(source=source):
                self.assertIn(clause, step_three)
        self.assertIn("The first three are fixed content. Each such pick becomes an incoming issue in "
                      "`Habit130/agent-repo-governance`, quoting habit's decision.", step_three)

    def test_class_retro_is_a_rendered_fixed_reference(self):
        manifest = store.Store(support.REAL_STORE).manifest(self.VERSION)
        self.assertIn({"path": CLASS_RETRO, "class": "fixed", "mode": "100644"}, manifest["templates"])
        notice = "<!-- Generated by governance model version %d. Only the generator changes this file. -->" % self.VERSION
        self.assertEqual(self.text(CLASS_RETRO).splitlines()[0], notice)

    def test_class_retro_routes_issue_setup_before_reviewing_the_window(self):
        intro = self.text(CLASS_RETRO).split("\n1. **Window.**", 1)[0]
        self.assertIn("Before step 1, follow [Planner → Tickets](planner.md#tickets), The dispatch plan, "
                      "to establish this run's issue.", flat(intro))

    def test_class_retro_keeps_seven_ordered_steps(self):
        path = Path(self.dest) / CLASS_RETRO
        body = path.read_text() if path.is_file() else ""
        steps = re.split(r"(?m)^(\d+)\. ", body)[1:]
        step_bodies = dict(zip(steps[::2], steps[1::2]))
        for step, (heading, clauses) in enumerate((
            ("Window", (
                "Take every PR merged after the last one the previous class retro covered.",
                "For the first class retro, take every PR merged since the repository's Initialize.",
                "Done when the window's first and last PR are named.",
            )),
            ("Occurrences", (
                "Read each PR's inline review comments, Comment review bodies and bot findings, with the Builder's answers.",
                "An occurrence is a confirmed Important-level finding: a Reviewer's Important, a review bot's P0 or P1 "
                "or its stated equivalent, a security review's HIGH or MEDIUM, or an escape.",
                "A finding rejected with evidence is none, and a Nit only supports a class that qualifies.",
                "Done when every PR in the window is listed with its occurrences, or with none.",
            )),
            ("Classes", (
                "Give each occurrence one primary bug class: the class whose fix would have caught it.",
                "A class qualifies once it has occurrences in two different PRs, counting earlier class retros' baselines.",
                "Done when every occurrence has its class.",
            )),
            ("Enforcement", (
                "For each qualifying class, name the rule text that addresses it and what checks it today: "
                "the gate, Merge watch, CI, a repository test or review judgment only.",
                "Read it from the code and tests at the window's last commit, and keep no standing copy.",
                "Done when every qualifying class has its row.",
            )),
            ("Evidence binding", (
                "For each PR in the window, check that its final evidence comment names the PR's final head by full SHA.",
                "A merged PR without one is a process miss: open a miss record of category `other` "
                "(`issue-tracker.md`, Miss records).",
                "Done when every PR in the window is checked.",
            )),
            ("Recurrence", (
                "For each class in the previous class retro's baseline, compare its last occurrence with the fix in force.",
                "Done when each has a status: held, recurred or too early.",
                "On the first class retro, there is no previous baseline to compare.",
            )),
            ("Report", (
                "Post one comment on this class retro's issue with the window, the occurrences by class, the enforcement "
                "view, the evidence-binding result, each class's recurrence status and the candidates under "
                "`planner.md`, Running retro.",
                "Set a new baseline, the first if this is the first class retro. Give each class's last occurrence, "
                "the fix in force and what the next class retro checks.",
                "Then give habit the candidates in Chinese, by severity. Follow step 3 of `planner.md`, Running retro, "
                "for habit's picks. Record habit's decision on the issue and follow The dispatch plan to close it.",
            )),
        ), start=1):
            with self.subTest(step=step, heading=heading):
                shown = flat(step_bodies.get(str(step), ""))
                self.assertTrue(shown.startswith("**%s.** " % heading), shown)
                for clause in clauses:
                    self.assertIn(clause, shown)
        self.assertEqual(steps[::2], [str(i) for i in range(1, 8)])
        for pilot_text in ("During the pilot", "retro #226", "The pilot's end"):
            self.assertNotIn(pilot_text, body)

