"""The governance record (#44 §4): version 1's record template, read back through the machine parser.

Every parser's verdict on the format itself comes from the shared parser fixtures
(`test_parser_fixtures.py`). This suite covers what is the machine side's own: version 1's
template, rendering's confirmed values read back, and the parser's refusals naming a line.
"""

import json
import os
import unittest

import materialized
import support
from govlib import GovernError, record, store

RECORD = ".github/governance/record.yml"
SHARED = os.path.join(support.FIXTURES, "parsers", "record")

# #41 §4's default sensitive paths, each with a medium floor.
DEFAULT_PATTERNS = [
    "**/AGENTS.md",
    "**/AGENTS.override.md",
    "**/CLAUDE.md",
    "docs/agents/**",
    ".claude/**",
    ".opencode/**",
    "opencode.json",
    ".dsh/**",
    ".agents/**",
    ".codex/**",
    ".cursor/**",
    ".github/**",
]
NOTICE = (
    "# Generated by governance model version 1, except `confirmed`. Only the generator changes the rest; "
    "`confirmed` follows AGENTS.md, Governance files.\n"
)

TALLY = materialized.tally_fixture()["confirmed"]
EMPTY = {"sensitive_paths": [], "required_checks": []}
# Confirmed values whose text YAML would misread unquoted, or that need escaping.
AWKWARD = {
    "sensitive_paths": [
        {"pattern": 'src/"quoted"/**', "floor": "high"},
        {"pattern": "src\\windows\\path", "floor": "medium"},
        {"pattern": "src/a: b # c", "floor": "high"},
        {"pattern": "*", "floor": "high"},
        {"pattern": "  spaced  ", "floor": "medium"},
        {"pattern": "docs/über/**", "floor": "medium"},
        {"pattern": "/leading/slash", "floor": "medium"},
    ],
    "required_checks": ["CI / test", "nightly @@version@@", "yes", "null", "2024", "-dash", "#hash", "'single'"],
}


class RenderedRecord(support.TempDirCase):
    def render(self, confirmed):
        """Render version 1 from the real store into a fresh temporary directory; return (code, facts, dest)."""
        dest = self.path("out-%d" % len(os.listdir(self.tmp)))
        values = self.path("confirmed-%d.json" % len(os.listdir(self.tmp)))
        with open(values, "w") as handle:
            json.dump(confirmed, handle)
        code, facts = support.govern(
            [
                "render", "--store", support.REAL_STORE, "--version", "1", "--allow-unreleased",
                "--dest", dest, "--repository", "Habit130/tally", "--default-branch", "main",
                "--confirmed", values,
            ]
        )
        return code, facts, dest

    def read_back(self, confirmed):
        code, facts, dest = self.render(confirmed)
        self.assertEqual(code, 0, facts)
        with open(os.path.join(dest, *RECORD.split("/")), "rb") as handle:
            data = handle.read()
        return data, dest


class VersionOneRecordTemplate(RenderedRecord):
    def test_the_manifest_lists_the_record_template_with_class_record(self):
        manifest = store.Store(support.REAL_STORE).manifest(1)
        records = [entry for entry in manifest["templates"] if entry["class"] == "record"]
        self.assertEqual(records, [{"path": RECORD, "class": "record", "mode": "100644"}])

    def test_rendered_with_sample_confirmed_values_it_reads_back_through_the_parser(self):
        for confirmed in (TALLY, EMPTY, AWKWARD):
            data, _ = self.read_back(confirmed)
            self.assertEqual(
                record.parse(data),
                {
                    "version": 1,
                    "agent_account": "Habit098",
                    "sensitive_paths": [{"pattern": pattern, "floor": "medium"} for pattern in DEFAULT_PATTERNS],
                    "confirmed": confirmed,
                },
            )

    def test_its_first_line_is_the_generated_notice_exempting_confirmed(self):
        data, _ = self.read_back(TALLY)
        self.assertEqual(data.decode("utf-8").split("\n")[0] + "\n", NOTICE)

    def test_the_shared_tally_fixture_is_what_version_one_renders_for_tally(self):
        data, _ = self.read_back(TALLY)
        with open(os.path.join(SHARED, "tally.yml"), "rb") as handle:
            self.assertEqual(data, handle.read())

    def test_a_fresh_render_with_awkward_values_has_no_differences(self):
        _, dest = self.read_back(AWKWARD)
        support.init_repo(dest)
        code, facts = support.govern(
            ["compare", "--store", support.REAL_STORE, "--version", "1", "--allow-unreleased", "--worktree", dest,
             "--repository", "Habit130/tally", "--default-branch", "main"]
        )
        self.assertEqual((code, facts["differences"]), (0, []), facts)
        self.assertIn(RECORD, facts["checked"])


class ConfirmedValuesTheParserRefuses(RenderedRecord):
    def test_rendering_refuses_them_and_writes_nothing(self):
        for text in (
            "line\u2028separator", "next\u0085line", "byte\ufefforder", "a\ttab", "c1\x9bcontrol",
            "non\uffffcharacter", "lone\ud800surrogate", "",
        ):
            for confirmed in (
                {"sensitive_paths": [{"pattern": text, "floor": "high"}], "required_checks": []},
                {"sensitive_paths": [], "required_checks": [text]},
            ):
                code, facts, dest = self.render(confirmed)
                self.assertEqual(code, 2, (confirmed, facts))
                self.assertFalse(os.path.exists(dest), confirmed)


class MachineParserRefusals(unittest.TestCase):
    def test_a_refusal_is_a_governance_error_naming_the_line(self):
        with open(os.path.join(SHARED, "floor-low.yml"), "rb") as handle:
            data = handle.read()
        with self.assertRaises(record.RecordError) as caught:
            record.parse(data)
        self.assertIsInstance(caught.exception, GovernError)
        self.assertIn("line 9", str(caught.exception))
        self.assertIn("low", str(caught.exception))


if __name__ == "__main__":
    unittest.main()
