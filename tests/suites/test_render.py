"""Rendering (#44 §4): a version, the repository's values and confirmed values become files."""

import json
import os
import shutil
import unittest

import support

FOUR_CLASSES = os.path.join(support.FIXTURES, "stores", "four-classes")
VALUES = ["--repository", "Habit130/tally", "--default-branch", "main"]

TALLY_CONFIRMED = {
    "sensitive_paths": [
        {"pattern": "src/sync/auth.ts", "floor": "medium"},
        {"pattern": "scripts/release.sh", "floor": "high"},
    ],
    "required_checks": ["test"],
}

EXPECTED_RECORD = """# Generated by governance model version 1, except `confirmed`. Only the generator changes the rest.
version: 1
agent_account: Habit098
sensitive_paths:
  - pattern: "**/AGENTS.md"
    floor: medium
confirmed:
  sensitive_paths:
    - pattern: "src/sync/auth.ts"
      floor: medium
    - pattern: "scripts/release.sh"
      floor: high
  required_checks:
    - "test"
"""

EXPECTED_REVIEW = """<!-- Generated by governance model version 1. Only the generator changes this file. -->

# Review

Reviews of `Habit130/tally` run against `main`.
"""


class RenderCase(support.TempDirCase):
    def store_copy(self, released=True):
        root = self.path("store")
        shutil.copytree(FOUR_CLASSES, root)
        if not released:
            os.remove(os.path.join(root, "1", "change-note.md"))
        return root

    def confirmed_file(self, confirmed):
        path = self.path("confirmed.json")
        with open(path, "w") as handle:
            json.dump(confirmed, handle)
        return path

    def render(self, store, dest, confirmed=TALLY_CONFIRMED, extra=(), values=VALUES, env=None):
        args = ["render", "--store", store, "--dest", dest] + list(values) + list(extra)
        if confirmed is not None:
            args += ["--confirmed", self.confirmed_file(confirmed)]
        return support.govern(args, env=env)

    def rendered_files(self, dest):
        found = {}
        for root, _, files in os.walk(dest):
            for name in files:
                full = os.path.join(root, name)
                found[os.path.relpath(full, dest).replace(os.sep, "/")] = support.read_text(full)
        return found


class Rendering(RenderCase):
    def test_renders_every_class_with_the_repositorys_values(self):
        dest = self.path("out")
        code, facts = self.render(self.store_copy(), dest)
        self.assertEqual(code, 0, facts)
        self.assertEqual(facts["version"], 1)
        self.assertEqual(
            sorted(facts["written"]),
            [
                ".claude/CLAUDE.md",
                ".github/governance/owner.sh",
                ".github/governance/record.yml",
                "AGENTS.md",
                "docs/agents/build.md",
                "docs/agents/review.md",
            ],
        )
        files = self.rendered_files(dest)
        self.assertEqual(files["docs/agents/review.md"], EXPECTED_REVIEW)
        self.assertEqual(files[".github/governance/record.yml"], EXPECTED_RECORD)
        self.assertTrue(files["AGENTS.md"].startswith("<!-- governance:begin v1 -->\n"))
        self.assertIn("The tracker is `Habit130/tally`, and deliveries start from `origin/main`.", files["AGENTS.md"])
        self.assertEqual(support.file_mode(os.path.join(dest, ".github", "governance", "owner.sh")), "100755")
        self.assertEqual(support.file_mode(os.path.join(dest, "docs", "agents", "review.md")), "100644")
        for path, text in files.items():
            self.assertNotIn("@@", text, path)

    def test_writes_an_empty_confirmed_list_as_a_key_without_items(self):
        dest = self.path("out")
        code, facts = self.render(self.store_copy(), dest, confirmed={"sensitive_paths": [], "required_checks": []})
        self.assertEqual(code, 0, facts)
        record = support.read_text(os.path.join(dest, ".github", "governance", "record.yml"))
        self.assertTrue(record.endswith("confirmed:\n  sensitive_paths:\n  required_checks:\n"), record)

    def test_refuses_values_that_are_not_a_repository_or_a_branch(self):
        for values in (
            ["--repository", "tally", "--default-branch", "main"],
            ["--repository", "Habit130/tally", "--default-branch", "two words"],
            ["--repository", "Habit130/tally", "--default-branch", "@@version@@"],
        ):
            code, facts = self.render(self.store_copy(), self.path("out"), values=values)
            self.assertEqual(code, 2, values)
            self.assertFalse(os.path.exists(self.path("out")), values)
            shutil.rmtree(self.path("store"))


class ConfirmedValues(RenderCase):
    def test_render_only_into_the_records_confirmed_part(self):
        dest = self.path("out")
        distinctive = {
            "sensitive_paths": [{"pattern": "src/zz-distinctive-auth/**", "floor": "high"}],
            "required_checks": ["zz-distinctive-check"],
        }
        code, facts = self.render(self.store_copy(), dest, confirmed=distinctive)
        self.assertEqual(code, 0, facts)
        for path, text in self.rendered_files(dest).items():
            if path == ".github/governance/record.yml":
                head, _, confirmed_part = text.partition("\nconfirmed:\n")
                self.assertIn("zz-distinctive-auth", confirmed_part)
                self.assertIn("zz-distinctive-check", confirmed_part)
                self.assertNotIn("zz-distinctive", head)
            else:
                self.assertNotIn("zz-distinctive", text, path)

    def test_token_like_text_in_a_confirmed_value_is_kept_verbatim(self):
        dest = self.path("out")
        confirmed = {"sensitive_paths": [], "required_checks": ["nightly @@version@@"]}
        code, facts = self.render(self.store_copy(), dest, confirmed=confirmed)
        self.assertEqual(code, 0, facts)
        record = support.read_text(os.path.join(dest, ".github", "governance", "record.yml"))
        self.assertIn('    - "nightly @@version@@"\n', record)

    def test_refuses_malformed_confirmed_values(self):
        for confirmed in (
            {"sensitive_paths": [{"pattern": "src/**", "floor": "low"}], "required_checks": []},
            {"sensitive_paths": [], "required_checks": ["two\nlines"]},
            {"sensitive_paths": [], "required_checks": [], "agent_account": "someone"},
            {"sensitive_paths": [{"pattern": "src/**"}], "required_checks": []},
        ):
            code, facts = self.render(self.store_copy(), self.path("out"), confirmed=confirmed)
            self.assertEqual(code, 2, confirmed)
            self.assertFalse(os.path.exists(self.path("out")), confirmed)
            shutil.rmtree(self.path("store"))

    def test_a_record_template_needs_confirmed_values(self):
        code, facts = self.render(self.store_copy(), self.path("out"), confirmed=None)
        self.assertEqual(code, 2)
        self.assertIn("confirmed", facts["error"])


class Tokens(RenderCase):
    def with_review_text(self, text):
        store = self.store_copy()
        with open(os.path.join(store, "1", "templates", "docs", "agents", "review.md"), "w") as handle:
            handle.write(text)
        return store

    def test_fails_on_an_unknown_token_and_writes_nothing(self):
        store = self.with_review_text("# Review\n\nOwner: @@owner@@\n")
        dest = self.path("out")
        code, facts = self.render(store, dest)
        self.assertEqual(code, 2)
        self.assertIn("@@owner@@", facts["error"])
        self.assertIn("docs/agents/review.md", facts["error"])
        self.assertIn("line 3", facts["error"])
        self.assertFalse(os.path.exists(dest))

    def test_fails_on_a_leftover_token(self):
        for text in ("# Review\n\nVersion @@version@ only\n", "# Review\n\nVersion @version@@ only\n", "@@default_branch\n"):
            store = self.with_review_text(text)
            code, facts = self.render(store, self.path("out"))
            self.assertEqual(code, 2, text)
            self.assertIn("leftover", facts["error"], text)
            shutil.rmtree(self.path("store"))

    def test_keeps_text_that_merely_contains_at_signs(self):
        text = "# Review\n\n```diff\n@@ -1,2 +1,2 @@\n```\n\nMail habit@@example.invalid? No: @@ alone is text.\n"
        store = self.with_review_text(text.replace("habit@@example", "habit@example"))
        dest = self.path("out")
        code, facts = self.render(store, dest)
        self.assertEqual(code, 0, facts)
        rendered = support.read_text(os.path.join(dest, "docs", "agents", "review.md"))
        self.assertIn("@@ -1,2 +1,2 @@", rendered)


class UnreleasedVersions(RenderCase):
    def test_an_unreleased_version_renders_only_when_the_run_asks(self):
        store = self.store_copy(released=False)
        code, facts = self.render(store, self.path("refused"), extra=["--version", "1"])
        self.assertEqual(code, 2)
        self.assertIn("not released", facts["error"])
        self.assertFalse(os.path.exists(self.path("refused")))

        code, facts = self.render(store, self.path("asked"), extra=["--version", "1", "--allow-unreleased"])
        self.assertEqual(code, 0, facts)
        self.assertFalse(facts["released"])

        code, facts = self.render(store, self.path("again"), extra=["--version", "1"])
        self.assertEqual(code, 2, "the opt-in must not outlive the run that asked")

    def test_a_store_with_no_released_version_stops_a_normal_render(self):
        store = self.store_copy(released=False)
        for extra in ([], ["--allow-unreleased"]):
            code, facts = self.render(store, self.path("out"), extra=extra)
            self.assertEqual(code, 2, extra)
            self.assertIn("no released version", facts["error"])
            self.assertFalse(os.path.exists(self.path("out")))

    def test_a_normal_render_writes_the_installed_version(self):
        store = self.store_copy()
        shutil.copytree(os.path.join(store, "1"), os.path.join(store, "2"))
        manifest_path = os.path.join(store, "2", "manifest.json")
        with open(manifest_path) as handle:
            manifest = json.load(handle)
        manifest["version"] = 2
        with open(manifest_path, "w") as handle:
            json.dump(manifest, handle)
        os.remove(os.path.join(store, "2", "change-note.md"))
        code, facts = self.render(store, self.path("out"))
        self.assertEqual((code, facts.get("version")), (0, 1), facts)


class IntoAWorktree(RenderCase):
    def worktree(self, files):
        target = support.init_repo(self.path("target"))
        support.write_tree(target, files)
        return target

    def test_replaces_only_the_fixed_part_and_keeps_repository_owned_content(self):
        target = self.worktree(
            {
                "AGENTS.md": "Intro kept.\n<!-- governance:begin v1 -->\nold fixed text\n<!-- governance:end -->\n\n## This repository\n\nCarried rule.\n",
                "docs/agents/build.md": "# Build\n\nnpm test\n",
                "src/app.ts": "export {}\n",
            }
        )
        env = support.isolated_env({"TMPDIR": self.path("tmpdir")})
        os.makedirs(self.path("tmpdir"))
        code, facts = self.render(self.store_copy(), target, env=env)
        self.assertEqual(code, 0, facts)
        agents = support.read_text(os.path.join(target, "AGENTS.md"))
        self.assertTrue(agents.startswith("Intro kept.\n<!-- governance:begin v1 -->\n# AGENTS.md\n"), agents)
        self.assertTrue(agents.endswith("<!-- governance:end -->\n\n## This repository\n\nCarried rule.\n"), agents)
        self.assertNotIn("old fixed text", agents)
        self.assertNotIn("Skeleton", agents)
        self.assertEqual(support.read_text(os.path.join(target, "docs", "agents", "build.md")), "# Build\n\nnpm test\n")
        self.assertEqual(facts["kept"], ["docs/agents/build.md"])
        self.assertEqual(support.read_text(os.path.join(target, "src", "app.ts")), "export {}\n")

    def test_refuses_a_mixed_file_without_well_formed_markers_and_writes_nothing(self):
        for text in (
            "# Agents from another process\n",
            "<!-- governance:begin v1 -->\na\n<!-- governance:begin v1 -->\nb\n<!-- governance:end -->\n",
            "<!-- governance:end -->\n<!-- governance:begin v1 -->\n",
        ):
            target = self.worktree({"AGENTS.md": text})
            code, facts = self.render(self.store_copy(), self.path("target"))
            self.assertEqual(code, 2, text)
            self.assertIn("AGENTS.md", facts["error"])
            self.assertFalse(os.path.exists(os.path.join(target, "docs", "agents", "review.md")), text)
            self.assertEqual(support.read_text(os.path.join(target, "AGENTS.md")), text)
            shutil.rmtree(target)
            shutil.rmtree(self.path("store"))

    def test_refuses_a_target_whose_parent_is_a_symlink_or_a_file_and_writes_nothing(self):
        outside = self.path("outside")
        os.makedirs(outside)
        for plant in ("symlink", "file"):
            target = support.init_repo(self.path("target"))
            if plant == "symlink":
                os.symlink(outside, os.path.join(target, "docs"))
            else:
                support.write_tree(target, {"docs": "a file where a directory goes\n"})
            code, facts = self.render(self.store_copy(), target)
            self.assertEqual(code, 2, (plant, facts))
            self.assertIn("docs", facts["error"])
            self.assertEqual(os.listdir(outside), [], plant)
            self.assertFalse(os.path.exists(os.path.join(target, "AGENTS.md")), plant)
            shutil.rmtree(target)
            shutil.rmtree(self.path("store"))


